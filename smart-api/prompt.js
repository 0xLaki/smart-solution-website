function plural(n, one, few, many) {
  const a = Math.abs(n) % 100, b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b === 1) return one;
  if (b > 1 && b < 5) return few;
  return many;
}

// st: { services, works, name, contactKinds, telegramLogin, userCount, handoffMin, canHandoff, handedOff,
//       brief, returning, voice }
function systemPrompt(st) {
  const now = [];
  now.push("Ты уже поздоровался так: «" + GREETING + "»");
  now.push(st.name ? "Посетителя зовут " + st.name + "." : "Имя посетителя пока неизвестно.");
  if (st.contactKinds && st.contactKinds.length) {
    now.push("Контакт для связи уже есть (" + st.contactKinds.join(", ") + "), больше его не спрашивай.");
  } else {
    now.push(
      "Контакта для связи пока нет. После ответа на вопрос посетителя попроси " + (st.name ? "" : "имя и ") + "Telegram или телефон" +
        (st.telegramLogin ? ", или предложи войти через Telegram кнопкой в чате — так разговор сохранится и на другом устройстве" : "") +
        ". Если человек не хочет оставлять контакт, не дави, но через пару сообщений попроси снова."
    );
  }
  now.push(
    "Посетитель написал " + st.userCount + " " + plural(st.userCount, "сообщение", "сообщения", "сообщений") +
      "; Михаил подключается после " + st.handoffMin + "."
  );
  if (st.handedOff) {
    now.push("Разговор уже передан Михаилу, он свяжется сам. Продолжай помогать и уточнять детали: Михаил видит продолжение.");
  } else if (st.canHandoff) {
    now.push("Задача описана достаточно: можно предложить позвать Михаила кнопкой в чате — он получит весь разговор. Если посетитель хочет, продолжай уточнять.");
  }
  if (st.brief) {
    if (st.brief.service) now.push("Подходящая услуга, по пересказу: " + st.brief.service + ".");
    if (st.brief.summary) now.push("Что уже известно: " + st.brief.summary);
    if (st.brief.missing && st.brief.missing.length) now.push("Ещё не выяснено: " + st.brief.missing.join("; ") + ".");
  }
  if (st.returning) now.push("Посетитель вернулся после перерыва: коротко поприветствуй его снова и напомни, на чём остановились.");
  if (st.voice) now.push("Последнее сообщение посетитель надиктовал голосом: в нём могут быть ошибки распознавания, понимай по смыслу.");

  return ROLE + "\n\nНаши услуги:\n" + st.services + "\n\nНаши работы:\n" + st.works + "\n\nСейчас в разговоре:\n" + now.map((l) => "- " + l).join("\n");
}

function extractPrompt(serviceNames) {
  return EXTRACT.replace("{services}", serviceNames.map((n) => "- " + n).join("\n"));
}

